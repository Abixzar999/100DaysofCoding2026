import java.util.Scanner;

public class days30 {
    public static void main(String[] args) {
        Scanner input = new Scanner(System.in);

        // Memasukkan nilai
        int a = input.nextInt();
        int b = input.nextInt();

        // Melakukan perbandingan sekaligus menampilkan hasilnya
        System.out.println("a <= b: " + (a <= b));
        System.out.println("a >= b: " + (a >= b));

        // Operator Perbandingan <= dan >=.

    }
}
