import java.util.Scanner;

public class days29 {
    public static void main(String[] args){
        Scanner input = new Scanner(System.in);
        
        // Memasukkan nilai
        System.out.print("a : ");
        int a = input.nextInt();
        System.out.print("b : ");
        int b = input.nextInt();

        // Menampilkan hasil dan melakukan perbandingan        
        System.out.println(a > b);
        System.out.println(a < b);

        // Operator Perbandingan < dan >.
    }
}
