
public class days3w {

    public static void main(String[] args) {

        System.out.println("Perkenalkan nama Saya Abizar Al Gifari\f"); // \f untuk membuat paragraf baru
        System.out.println("Abizar\tAl\tGifari"); // \t untuk tab atau spasi panjang
        System.out.println("\"Abizar Al Gifari\""); // \" untuk memberi tanda kutip 2 "
        System.out.println("Abizar\n Al \nGifari"); // \n untuk membuat baris bawah
        System.out.println("Abizar\b Al Gifari\b "); // \b untuk menghapus 1 karakter
        System.out.println("\'Abizar Al Gifari\'"); // \' untuk memberi tanda kutip 1 '
        System.out.println("Abizar\rAl \rGifari"); // \ untuk menimpa atau menggantikan teks
        System.out.println("Abizar\\Al\\Gifari"); // \\ untuk memberikan tanda slash

    }
}
