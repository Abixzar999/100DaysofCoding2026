import java.util.Scanner;

public class days27 {
    public static void main(String[] args) {
        Scanner input = new Scanner(System.in);

        // Memasukkan angka untuk Increment
        System.out.print("Masukkan angka untuk Increment : ");
        int angka1 = input.nextInt();

        // Memasukkan angka untuk Decrement
        System.out.print("Masukkan angka untuk Decrement : ");
        int angka2 = input.nextInt();

        // Melakukan penambahan 1
        angka1++;

        // Melakukan pengurangan 1
        angka2--;

        // menampilkan hasil
        System.out.println("Increment : " + angka1);
        System.out.println("Decrement : " + angka2);
        


        // Operator Increment dan Decrement (++, --)
    }
}
