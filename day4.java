    public static void main(String[] args) {

        // Byte untuk menyimpan bilangan bulat dengan nilai yang kecil
        byte level = 10;
        System.out.println("Level : " + level);

        // Short untuk menyimpan bilangan bulat dengan nilai sedang atau lebih besar dari Byte
        short jumlahkoin = 2400;
        System.out.println("Jumlah Koin : " + jumlahkoin);

        // Int untuk menyimpan bilangan bulat cukup besar
        // Tipe data ini yang sering digunakan untuk menyimpan bilangan bulat
        int hargaitem = 20000;
        System.out.println("Harga Item : " + hargaitem);

        long jumlahpemainonline = 1010000003000L;
        System.out.println("Jumlah Pemain Online : " + jumlahpemainonline);
        // Long untuk menyimpan bilagan bulat yang paling besar
        // Tipe data long biasanya penulisannya diakhiri dengan huruf L
        
    }
